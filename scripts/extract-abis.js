/**
 * CowrieChain ABI Extraction Script
 * Extracts exact compiled ABIs from Foundry build artifacts in contract/out
 * and writes them to frontend/src/lib/abis/ and backend/src/config/abis/
 */

const fs = require("fs");
const path = require("path");

const ROOT = path.resolve(__dirname, "..");
const OUT_DIR = path.join(ROOT, "contract", "out");
const FRONTEND_ABI_DIR = path.join(ROOT, "frontend", "src", "lib", "abis");
const BACKEND_ABI_DIR = path.join(ROOT, "backend", "src", "config", "abis");

const ARTIFACT_MAP = [
  {
    name: "MockUSDC",
    src: path.join(OUT_DIR, "MockUSDC.sol", "MockUSDC.json"),
  },
  {
    name: "SavingsVault",
    src: path.join(OUT_DIR, "SavingsGoal.sol", "SavingsVault.json"),
  },
  {
    name: "GroupSaveFactory",
    src: path.join(OUT_DIR, "GroupSaveFactory.sol", "GroupSaveFactory.json"),
  },
  {
    name: "GroupSave",
    src: path.join(OUT_DIR, "GroupSave.sol", "GroupSave.json"),
  },
];

function ensureDir(dir) {
  if (!fs.existsSync(dir)) {
    fs.mkdirSync(dir, { recursive: true });
  }
}

function run() {
  console.log("Extracting ABIs from Foundry artifacts...");
  ensureDir(FRONTEND_ABI_DIR);
  ensureDir(BACKEND_ABI_DIR);

  const exported = {};

  for (const item of ARTIFACT_MAP) {
    if (!fs.existsSync(item.src)) {
      throw new Error(`Artifact not found at ${item.src}. Run "forge build" in contract/ first.`);
    }

    const artifact = JSON.parse(fs.readFileSync(item.src, "utf-8"));
    let abi = artifact.abi;

    // For GroupSave, ensure backward compatibility for both "leave" and "leaveCircle"
    if (item.name === "GroupSave") {
      const hasLeave = abi.some((el) => el.type === "function" && el.name === "leave");
      const hasLeaveCircle = abi.some((el) => el.type === "function" && el.name === "leaveCircle");
      if (!hasLeave) {
        abi.push({
          type: "function",
          name: "leave",
          inputs: [],
          outputs: [],
          stateMutability: "nonpayable",
        });
      }
      if (!hasLeaveCircle) {
        abi.push({
          type: "function",
          name: "leaveCircle",
          inputs: [],
          outputs: [],
          stateMutability: "nonpayable",
        });
      }
    }

    exported[item.name] = abi;

    const jsonStr = JSON.stringify(abi, null, 2);
    fs.writeFileSync(path.join(FRONTEND_ABI_DIR, `${item.name}.json`), jsonStr, "utf-8");
    fs.writeFileSync(path.join(BACKEND_ABI_DIR, `${item.name}.json`), jsonStr, "utf-8");
    console.log(`  ✓ ${item.name} (${abi.length} ABI entries)`);
  }

  // Generate frontend index.js
  const frontendIndex = `// Auto-generated by scripts/extract-abis.js - DO NOT EDIT MANUALLY
export { default as MockUSDCAbi } from "./MockUSDC.json";
export { default as SavingsVaultAbi } from "./SavingsVault.json";
export { default as GroupSaveFactoryAbi } from "./GroupSaveFactory.json";
export { default as GroupSaveAbi } from "./GroupSave.json";
`;
  fs.writeFileSync(path.join(FRONTEND_ABI_DIR, "index.js"), frontendIndex, "utf-8");

  // Generate backend index.js
  const backendIndex = `// Auto-generated by scripts/extract-abis.js - DO NOT EDIT MANUALLY
const MockUSDCAbi = require("./MockUSDC.json");
const SavingsVaultAbi = require("./SavingsVault.json");
const GroupSaveFactoryAbi = require("./GroupSaveFactory.json");
const GroupSaveAbi = require("./GroupSave.json");

module.exports = {
  MockUSDCAbi,
  SavingsVaultAbi,
  GroupSaveFactoryAbi,
  GroupSaveAbi,
};
`;
  fs.writeFileSync(path.join(BACKEND_ABI_DIR, "index.js"), backendIndex, "utf-8");

  console.log("ABI extraction complete!");
}

run();

